#!/usr/bin/env python3
"""Regenerate <protein>/README.md and sauces/README.md indexes from frontmatter.

No dependencies. Reads simple `key: value` frontmatter only.
Usage: python3 tools/build_index.py   (from repo root, or anywhere)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"tools", ".git"}
STATUS_ORDER = {"rotation": 0, "tested": 1, "draft": 2, "idea": 3}


def frontmatter(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" in line:
            key, _, val = line.partition(":")
            meta[key.strip()] = val.split("#", 1)[0].strip()
    return meta


def build(folder: Path) -> None:
    recipes = sorted(p for p in folder.rglob("*.md") if p.name != "README.md")
    if not recipes:
        return
    groups: dict[str, list] = {}
    for p in recipes:
        meta = frontmatter(p)
        sub = str(p.parent.relative_to(folder)) if p.parent != folder else ""
        groups.setdefault(sub, []).append((p, meta))

    out = [f"# {folder.name.capitalize()}", "", "_Generated by tools/build_index.py — do not edit._", ""]
    for sub in sorted(groups):
        if sub:
            out += [f"## {sub}", ""]
        items = sorted(groups[sub], key=lambda x: (STATUS_ORDER.get(x[1].get("status", ""), 9), x[0].name))
        for p, meta in items:
            title = meta.get("title") or p.stem
            method = meta.get("method", "")
            status = meta.get("status", "")
            rel = p.relative_to(folder).as_posix()
            tail = " · ".join(x for x in (method, status) if x)
            out.append(f"- [{title}]({rel})" + (f" — {tail}" if tail else ""))
        out.append("")
    (folder / "README.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {(folder / 'README.md').relative_to(ROOT)}")


if __name__ == "__main__":
    for d in sorted(ROOT.iterdir()):
        if d.is_dir() and d.name not in SKIP and not d.name.startswith("."):
            build(d)
